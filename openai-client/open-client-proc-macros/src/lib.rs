use proc_macro::TokenStream;
use quote::quote;
use syn::{
    Attribute, Data, DeriveInput, Fields, FnArg, ItemFn, Lit, Meta, Pat, Type, parse_macro_input,
};

/// Attribute macro to mark a function as callable by the model.
///
/// This macro generates a schema for the function and an `execute` method to call it
/// with JSON arguments.
///
/// # Requirements
/// - Function arguments must be owned types that implement `OpenAISchema` (e.g., `String`, `i32`, `bool`).
/// - References are not supported.
/// - The function can be `async` and can return a `Result` (the `Ok` value must implement `Serialize`).
///
/// # Example
/// ```ignore
/// #[openai_function]
/// /// Returns the current weather for a location.
/// fn get_weather(location: String) -> String {
///     format!("The weather in {} is sunny.", location)
/// }
/// ```
#[proc_macro_attribute]
pub fn openai_function(_attr: TokenStream, item: TokenStream) -> TokenStream {
    let mut input_fn = parse_macro_input!(item as ItemFn);
    let fn_name = &input_fn.sig.ident;
    let vis = &input_fn.vis;
    let fn_description = extract_doc_comments(&input_fn.attrs);

    let mut properties = Vec::new();
    let mut required = Vec::new();
    let mut param_names = Vec::new();
    let mut param_types = Vec::new();

    for arg in input_fn.sig.inputs.iter_mut() {
        let FnArg::Typed(pat_type) = arg else {
            return syn::Error::new_spanned(arg, "methods are not supported in openai_function")
                .to_compile_error()
                .into();
        };
        let Pat::Ident(pat_ident) = &*pat_type.pat else {
            return syn::Error::new_spanned(
                &pat_type.pat,
                "openai_function arguments must be plain names, as they are the JSON keys",
            )
            .to_compile_error()
            .into();
        };
        let param_name = pat_ident.ident.clone();
        let param_name_str = param_name.to_string();
        let param_type = (*pat_type.ty).clone();
        let param_desc = extract_doc_comments(&pat_type.attrs);

        if has_reference(&param_type) {
            return syn::Error::new_spanned(
                &param_type,
                "references are not supported in openai_function. Use owned types like String instead.",
            )
            .to_compile_error()
            .into();
        }

        // Remove doc attributes from the function signature so it compiles
        pat_type.attrs.retain(|attr| !attr.path().is_ident("doc"));

        let schema = with_description(
            quote! { <#param_type as ::open_client::OpenAISchema>::openai_schema() },
            &param_desc,
        );
        properties.push(quote! { props.insert(#param_name_str.to_string(), #schema); });

        // `Option` is nullable but still required, as needed by strict mode.
        required.push(param_name_str);

        param_names.push(param_name);
        param_types.push(param_type);
    }

    let fn_name_str = fn_name.to_string();
    let is_async = input_fn.sig.asyncness.is_some();
    let call_await = if is_async {
        quote! { .await }
    } else {
        quote! {}
    };

    let is_result = match &input_fn.sig.output {
        syn::ReturnType::Default => false,
        syn::ReturnType::Type(_, ty) => {
            let s = quote!(#ty).to_string();
            s.contains("Result")
        }
    };

    let result_handling = if is_result {
        quote! {
            match result {
                Ok(v) => Ok(::open_client::serde_json::json!(v)),
                Err(e) => Err(e.to_string()),
            }
        }
    } else {
        quote! {
            Ok(::open_client::serde_json::json!(result))
        }
    };

    let schema = with_description(
        quote! {
            json!({
                "name": #fn_name_str,
                "parameters": {
                    "type": "object",
                    "properties": props,
                    "required": [#(#required),*],
                    "additionalProperties": false
                }
            })
        },
        &fn_description,
    );
    let props = build_props(&properties);

    // The struct has the function's name and visibility, so `fn_name::openai_schema()` works
    // wherever the function can be called. Braced, so it doesn't clash with the function.
    let expanded = quote! {
        #input_fn

        #[allow(non_camel_case_types)]
        #vis struct #fn_name { }

        impl ::open_client::OpenAISchema for #fn_name {
            fn openai_schema() -> ::open_client::serde_json::Value {
                use ::open_client::serde_json::{json, Map};
                #props
                #schema
            }
        }

        impl #fn_name {
            /// Parses the arguments generated by the model, and calls the function with them.
            pub async fn execute(args: &::open_client::serde_json::Value) -> Result<::open_client::serde_json::Value, String> {
                let (#(#param_names,)*) = Self::parse_arguments(args).map_err(|e| e.to_string())?;
                let result = #fn_name(#(#param_names),*) #call_await;
                #result_handling
            }
            /// Parses the arguments generated by the model into a tuple of the function's arguments.
            pub fn parse_arguments(args: &::open_client::serde_json::Value) -> Result<(#(#param_types,)*), ::open_client::serde_json::Error>
            {
                #[derive(::open_client::serde::Deserialize)]
                #[serde(crate = "::open_client::serde")]
                struct Arguments {
                    #(#param_names: #param_types,)*
                }
                let args = <Arguments as ::open_client::serde::Deserialize>::deserialize(args)?;
                Ok((#(args.#param_names,)*))
            }
        }
    };

    expanded.into()
}

/// Macro to execute pending function calls requested by the model and update the session history, with a custom callback for results.
///
/// # Usage
/// `execute_function_calls_with_callback!(session, callback, function1, function2, ...)`
///
/// The `callback` should be a closure or function that takes `(String, Result<serde_json::Value, String>)`,
/// i.e. (function_name, result), and returns anything `Serialize`. It is sent as the tool result:
/// strings as they are, everything else as JSON.
///
/// # Returns
/// A `Vec<Option<Result<serde_json::Value, String>>>` containing the results of each function call.
/// - `Some(Ok(value))` if the function was called and succeeded.
/// - `Some(Err(err))` if the function was called but failed.
/// - `None` if the function was not called.
///
/// # Note
/// The `session` is automatically updated with a tool message per call.
/// The `callback` is invoked with the result of the function execution (whether `Ok` or `Err`)
/// and its return value is used to update the session.
#[proc_macro]
pub fn execute_function_calls_with_callback(input: TokenStream) -> TokenStream {
    use syn::parse::{Parse, ParseStream};
    use syn::{Expr, Token};

    struct ExecuteWithCallbackInput {
        session: Expr,
        _comma1: Token![,],
        callback: Expr,
        _comma2: Token![,],
        functions: syn::punctuated::Punctuated<syn::Path, Token![,]>,
    }

    impl Parse for ExecuteWithCallbackInput {
        fn parse(input: ParseStream) -> syn::Result<Self> {
            Ok(ExecuteWithCallbackInput {
                session: input.parse()?,
                _comma1: input.parse()?,
                callback: input.parse()?,
                _comma2: input.parse()?,
                functions: input.parse_terminated(syn::Path::parse, Token![,])?,
            })
        }
    }

    let input = parse_macro_input!(input as ExecuteWithCallbackInput);
    generate_execute_logic(&input.session, &input.callback, &input.functions)
}

/// Attribute macro to derive the `OpenAISchema` trait for a struct or enum.
///
/// This allows the type to be used in structured output (`set_json_mode`) or as a parameter
/// in an `openai_function`.
///
/// # Requirements
/// - For structs: only named fields are supported.
/// - For enums: only unit variants (no data) are supported.
/// - Field/variant types must also implement `OpenAISchema`.
/// - Doc comments on fields and variants are extracted as descriptions in the schema.
///
/// # Example
/// ```ignore
/// #[openai_schema]
/// struct SearchResult {
///     /// The title of the page.
///     title: String,
///     /// The URL of the page.
///     url: String,
/// }
/// ```
#[proc_macro_attribute]
pub fn openai_schema(_attr: TokenStream, item: TokenStream) -> TokenStream {
    let input = parse_macro_input!(item as DeriveInput);
    let name = &input.ident;
    let (impl_generics, ty_generics, where_clause) = input.generics.split_for_impl();
    let description = extract_doc_comments(&input.attrs);

    let expanded = match &input.data {
        Data::Struct(data) => {
            let mut properties = Vec::new();
            let mut required = Vec::new();

            match &data.fields {
                Fields::Named(fields) => {
                    for field in &fields.named {
                        let field_name = field.ident.as_ref().unwrap();
                        let field_name_str = field_name.to_string();
                        let field_type = &field.ty;
                        let field_desc = extract_doc_comments(&field.attrs);

                        if has_reference(field_type) {
                            return syn::Error::new_spanned(
                                field_type,
                                "references are not supported in openai_schema. Use owned types instead.",
                            )
                            .to_compile_error()
                            .into();
                        }

                        let schema = with_description(
                            quote! { <#field_type as ::open_client::OpenAISchema>::openai_schema() },
                            &field_desc,
                        );
                        properties
                            .push(quote! { props.insert(#field_name_str.to_string(), #schema); });

                        // `Option` is nullable but still required, as needed by strict mode.
                        required.push(field_name_str);
                    }
                }
                fields => {
                    return syn::Error::new_spanned(
                        fields,
                        "openai_schema only supports structs with named fields",
                    )
                    .to_compile_error()
                    .into();
                }
            }

            let props = build_props(&properties);
            let schema = with_description(
                quote! {
                    json!({
                        "type": "object",
                        "properties": props,
                        "required": [#(#required),*],
                        "additionalProperties": false
                    })
                },
                &description,
            );
            quote! {
                impl #impl_generics ::open_client::OpenAISchema for #name #ty_generics #where_clause {
                    fn openai_schema() -> ::open_client::serde_json::Value {
                        use ::open_client::serde_json::{json, Map};
                        #props
                        #schema
                    }
                }
            }
        }
        Data::Enum(data) => {
            let mut variants = Vec::new();
            for variant in &data.variants {
                if !matches!(variant.fields, Fields::Unit) {
                    return syn::Error::new_spanned(
                        variant,
                        "openai_schema only supports unit variants in enums",
                    )
                    .to_compile_error()
                    .into();
                }
                variants.push(variant.ident.to_string());
            }

            let schema = with_description(
                quote! {
                    json!({
                        "type": "string",
                        "enum": [#(#variants),*]
                    })
                },
                &description,
            );
            quote! {
                impl #impl_generics ::open_client::OpenAISchema for #name #ty_generics #where_clause {
                    fn openai_schema() -> ::open_client::serde_json::Value {
                        use ::open_client::serde_json::json;
                        #schema
                    }
                }
            }
        }
        Data::Union(_) => {
            return syn::Error::new_spanned(name, "openai_schema only supports structs and enums")
                .to_compile_error()
                .into();
        }
    };

    let output = quote! {
        #input
        #expanded
    };

    output.into()
}

/// Schema expression with `"description"` added, if `description` isn't empty.
fn with_description(
    schema: proc_macro2::TokenStream,
    description: &str,
) -> proc_macro2::TokenStream {
    if description.is_empty() {
        return schema;
    }
    quote! {{
        let mut schema = #schema;
        if let Some(obj) = schema.as_object_mut() {
            obj.insert("description".to_string(), ::open_client::serde_json::json!(#description));
        }
        schema
    }}
}

/// Declares `props`, the map of `properties` of an object schema.
fn build_props(properties: &[proc_macro2::TokenStream]) -> proc_macro2::TokenStream {
    if properties.is_empty() {
        quote! { let props = Map::new(); }
    } else {
        quote! {
            let mut props = Map::new();
            #(#properties)*
        }
    }
}

fn extract_doc_comments(attrs: &[Attribute]) -> String {
    let mut doc_comments = Vec::new();
    for attr in attrs {
        if attr.path().is_ident("doc")
            && let Meta::NameValue(nv) = &attr.meta
            && let syn::Expr::Lit(expr_lit) = &nv.value
            && let Lit::Str(lit_str) = &expr_lit.lit
        {
            doc_comments.push(lit_str.value().trim().to_string());
        }
    }
    doc_comments.join("\n")
}

fn has_reference(ty: &Type) -> bool {
    match ty {
        Type::Reference(_) => true,
        Type::Path(tp) => {
            for seg in &tp.path.segments {
                if let syn::PathArguments::AngleBracketed(ab) = &seg.arguments {
                    for arg in &ab.args {
                        if let syn::GenericArgument::Type(inner) = arg
                            && has_reference(inner)
                        {
                            return true;
                        }
                    }
                }
            }
            false
        }
        _ => false,
    }
}

/// Macro to execute pending function calls requested by the model and update the session history.
///
/// # Usage
/// `execute_function_calls!(session, function1, function2, ...)`
///
/// # Returns
/// A `Vec<Option<Result<serde_json::Value, String>>>` containing the results of each function call.
/// The length of the vector matches the number of functions provided.
/// - `Some(Ok(value))` if the function was called and succeeded.
/// - `Some(Err(err))` if the function was called but failed.
/// - `None` if the function was not called.
///
/// # Note
/// The `session` is automatically updated with a tool message per call.
/// If a function call fails, the error is converted to a JSON object `{"Error": error_message}`
/// and sent to the session as the tool result.
/// Calls already responded (e.g. manually) are skipped.
#[proc_macro]
pub fn execute_function_calls(input: TokenStream) -> TokenStream {
    use syn::parse::{Parse, ParseStream};
    use syn::{Expr, Token};

    struct ExecuteInput {
        session: Expr,
        _comma: Token![,],
        functions: syn::punctuated::Punctuated<syn::Path, Token![,]>,
    }

    impl Parse for ExecuteInput {
        fn parse(input: ParseStream) -> syn::Result<Self> {
            Ok(ExecuteInput {
                session: input.parse()?,
                _comma: input.parse()?,
                functions: input.parse_terminated(syn::Path::parse, Token![,])?,
            })
        }
    }

    let input = parse_macro_input!(input as ExecuteInput);
    let callback: Expr = syn::parse_quote! {
        |_name: String, result: Result<::open_client::serde_json::Value, String>| {
            match result {
                Ok(value) => value,
                Err(e) => ::open_client::serde_json::json!({"Error": e}),
            }
        }
    };

    generate_execute_logic(&input.session, &callback, &input.functions)
}

fn generate_execute_logic(
    session: &syn::Expr,
    callback: &syn::Expr,
    functions: &syn::punctuated::Punctuated<syn::Path, syn::Token![,]>,
) -> TokenStream {
    let num_funcs = functions.len();

    let match_arms = functions.iter().enumerate().map(|(i, path)| {
        let name_str = path.segments.last().unwrap().ident.to_string();
        quote! {
            #name_str => {
                let args = call.args::<::open_client::serde_json::Value>();
                let fut: ::open_client::futures::future::BoxFuture<'static, (usize, String, String, Result<::open_client::serde_json::Value, String>)> = Box::pin(async move {
                    let result = match args {
                        Ok(args) => #path::execute(&args).await,
                        Err(e) => Err(format!("Invalid JSON arguments: {}", e)),
                    };
                    (#i, #name_str.to_string(), call_id, result)
                });
                futures.push(fut);
            }
        }
    });

    let expanded = quote! {
        {
            let mut results_array = vec![None; #num_funcs];
            // Define callback here to ensure it's available
            let mut result_callback = #callback;

            let mut futures = Vec::new();
            for call in #session.pending_tool_calls() {
                let call_id = call.id.clone();
                match call.function.name.as_str() {
                    #(#match_arms)*
                    _ => {}
                }
            }
            if !futures.is_empty() {
                let results = ::open_client::futures::future::join_all(futures).await;
                for (idx, name, call_id, res) in results {
                    // Invoke callback regardless of success or failure
                    let val_to_add = result_callback(name.clone(), res.clone());

                    if let Err(e) = #session.add_tool_result(&call_id, val_to_add) {
                        results_array[idx] = Some(Err(format!(
                            "failed to add tool result of `{}`: {}",
                            name, e
                        )));
                        continue;
                    }
                    results_array[idx] = Some(res);
                }
            }
            results_array
        }
    };

    expanded.into()
}
